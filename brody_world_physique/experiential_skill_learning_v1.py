"""Candidate learning loop: feedback trains a bounded residual skill, not merely model routing.

Frozen base forecasts are generated by existing motion modules. TRAIN errors
update a separate, hashed candidate skill. TEST receives no answer until grading.
"""
from __future__ import annotations
import argparse, hashlib, json, math
from pathlib import Path
from .f1b_physical_memory_bridge_v1 import episode
from .image_experience_guided_motion_v2 import forecast
from .image_observed_motion_school_v1 import analyze, render
from .image_multihypothesis_motion_memory_v1 import read
from .fusion_f9_intensive_education_v0 import digest

TRAIN=(("lesson_a",(10,14,20,28,39)),("lesson_b",(17,21,27,35,46)),
       ("interference_steady",(9,14,19,24,29)))
TEST=(("transfer_acceleration",(22,26,32,40,51)),
      ("different_start",(8,12,18,26,37)),
      ("contradiction_reversal",(11,15,21,29,25)))
SKILL="vertical|speeding_up"
def save(path,body):
    with Path(path).open("x",encoding="utf8") as f:json.dump(body,f,indent=2,sort_keys=True);f.write("\n")
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def seal(body):return {**body,"digest":digest(body)}
def inspect_skill(path):
    doc=read(path)
    h=doc.pop("digest",None)
    if h!=digest(doc) or doc.get("schema")!="BRODY_CANDIDATE_RESIDUAL_SKILL_V1":
        raise ValueError("INVALID_SKILL_SEAL")
    if doc.get("native_memory_write") is not False or doc.get("canonical_promotion") is not False or doc.get("decision_authority")!="KX108_ONLY":
        raise ValueError("INVALID_AUTHORITY")
    return doc
def run(out):
    root=Path(out)
    if root.exists():raise ValueError("PRESERVE_PRIOR_EVIDENCE")
    root.mkdir(parents=True)
    skill=seal({"schema":"BRODY_CANDIDATE_RESIDUAL_SKILL_V1",
        "model":"ACCELERATION","context":SKILL,"residuals":[],
        "preconditions":["4 timestamped segmented frames","matching context"],
        "dependencies":["visual_localization","temporal_order","acceleration_hypothesis"],
        "native_memory_write":False,"canonical_promotion":False,
        "decision_authority":"KX108_ONLY"})
    history=[];train_hashes=set()
    for index,(name,positions) in enumerate(TRAIN):
        manifest,truth=episode(root,name,positions,x=25+index*4)
        train_hashes.update(sha(Path(r["file"])) for r in read(manifest)["observations"])
        train_hashes.add(sha(truth))
        path=root/("pred_"+name)
        report=forecast(manifest,path)
        frozen=read(path/"sealed_forecast.json")
        model=frozen["hypotheses"]["ACCELERATION"]
        original_hash=sha(path/"sealed_forecast.json")
        observed=analyze(truth)  # Feedback becomes visible only after commitment.
        error=(round(observed["x"]-model["x"],6),round(observed["y"]-model["y"],6))
        if original_hash!=sha(path/"sealed_forecast.json"):raise ValueError("FORECAST_CHANGED")
        if report["context"]==SKILL:
            previous=skill["digest"]
            skill=inspect_skill_save(root/("skill_after_"+name+".json"),skill,error,sha(truth))
            history.append({"lesson":name,"skill_updated":True,"prior_digest":previous,
                "next_digest":skill["digest"],"error_xy_px":error})
        else:
            history.append({"lesson":name,"skill_updated":False,"context":report["context"],
                "error_xy_px":error})
    final_skill=root/"candidate_skill.json"
    save(final_skill,skill)
    loaded=inspect_skill(final_skill)
    if len(loaded["residuals"])!=2:raise ValueError("SKILL_RETENTION_FAILED")
    exams=[]
    for name,positions in TEST:
        manifest,truth=episode(root,name,positions,x=43)
        if sha(truth) in train_hashes or any(sha(Path(r["file"])) in train_hashes for r in read(manifest)["observations"]):
            raise ValueError("TRAIN_TEST_LEAK")
        path=root/("blind_"+name)
        report=forecast(manifest,path)
        sealed=read(path/"sealed_forecast.json")
        predicted=sealed["hypotheses"]["ACCELERATION"]
        eligible=report["context"]==loaded["context"] and len(loaded["residuals"])>=2
        mean_x=sum(e["dx"] for e in loaded["residuals"])/len(loaded["residuals"]) if eligible else 0.
        mean_y=sum(e["dy"] for e in loaded["residuals"])/len(loaded["residuals"]) if eligible else 0.
        adapted={**predicted,"x":predicted["x"]+mean_x,"y":predicted["y"]+mean_y}
        render(adapted,path/"candidate_adapted.png")
        frozen_sha=sha(path/"sealed_forecast.json")
        candidate_sha=sha(path/"candidate_adapted.png")
        commitment=seal({"case":name,"frozen_sha256":frozen_sha,
            "candidate_sha256":candidate_sha,"skill_digest":skill["digest"],
            "eligible":eligible,"predicted":adapted,"native_memory_write":False,
            "canonical_promotion":False,"decision_authority":"KX108_ONLY"})
        save(path/"pre_feedback_commit.json",commitment)
        # Only now reveal the test frame.
        real=analyze(truth)
        base_error=round(math.hypot(real["x"]-predicted["x"],real["y"]-predicted["y"]),5)
        new_error=round(math.hypot(real["x"]-adapted["x"],real["y"]-adapted["y"]),5)
        if frozen_sha!=sha(path/"sealed_forecast.json") or candidate_sha!=sha(path/"candidate_adapted.png"):
            raise ValueError("COMMIT_MUTATION")
        exams.append({"case":name,"context":report["context"],"candidate_eligible":eligible,
            "base_error_px":base_error,"adapted_error_px":new_error,
            "utility_px":round(base_error-new_error,5),"truth_not_available_until_commit":True})
    report={"schema":"BRODY_EXPERIENTIAL_SKILL_LEARNING_V1","lessons":history,
        "skill_file":"candidate_skill.json","skill_digest":skill["digest"],
        "skills_learned_by_error_correction":len(loaded["residuals"]),
        "exam":exams,"positive_transfer_cases":sum(x["utility_px"]>0 for x in exams),
        "negative_transfer_cases":sum(x["utility_px"]<0 for x in exams),
        "unchanged_cases":sum(x["utility_px"]==0 for x in exams),
        "interference_kept_skill":len(loaded["residuals"])==2,
        "train_test_hash_separated":True,"bounded_correction_not_law_discovery":True,
        "reverse_360_integrated":False,"sens_mmonde_integrated":False,
        "native_memory_write":False,"canonical_promotion":False,"decision_authority":"KX108_ONLY",
        "verdict":"EXPERIENTIAL_SKILL_CANDIDATE_ONLY"}
    save(root/"MASTER_REPORT.json",report)
    return report
def inspect_skill_save(path,skill,error,source_hash):
    verified=seal({k:v for k,v in skill.items() if k!="digest"})
    if verified["digest"]!=skill["digest"]:raise ValueError("SKILL_TAMPER")
    new={k:v for k,v in skill.items() if k!="digest"}
    new["residuals"]=new["residuals"]+[{"dx":error[0],"dy":error[1],"feedback_sha256":source_hash}]
    result=seal(new);save(path,result)
    return result
def main():
    p=argparse.ArgumentParser();p.add_argument("--out",required=True);a=p.parse_args()
    r=run(a.out)
    print(json.dumps({"verdict":r["verdict"],"positive_transfer_cases":r["positive_transfer_cases"],
        "negative_transfer_cases":r["negative_transfer_cases"],"unchanged_cases":r["unchanged_cases"]},indent=2))
if __name__=="__main__":main()
